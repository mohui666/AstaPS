"""Build MGC-authored battle groups from the installed official enemy previews.

Enemy kinds and levels come from TowerLevel/MonsterPreview. Counts, positions,
wave boundaries and Lua below are MGC's implementation, not official server Lua.
Existing scene stubs are preserved; scripts without this tool's first-line marker
are never overwritten. Remove that marker before manually editing generated Lua
to protect the edit from a later generation. No content comparison is performed.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

MARKER = '-- Generated by MGC tools/tower/generate_current_abyss.py'
HEADER = MARKER + '\n-- Official preview kinds/levels; MGC-authored counts, waves, positions and battle flow.\n'
SPECIAL_VARIANTS = {
    21003: (22100301, 'MonsterExcel affix 21003 selects the Hydro/Pyro/Electro Baptist variant'),
    30771: (23077101, 'Female healer variant; Describe 30771 and base 30761 share name and icon'),
    51315: (25131501, 'Sword variant 02; Describe 51315 and base 51314 share name and icon'),
}


def read_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def lua_list(values):
    return '{ ' + ', '.join(map(str, values)) + ' }'


def gadget(config, model, x=0, y=-0.102, z=0):
    return f'{{ config_id = {config}, gadget_id = {model}, pos = {{ x = {x:.3f}, y = {y:.3f}, z = {z:.3f} }}, rot = {{ x = 0, y = 0, z = 0 }}, level = 1 }}'


def trigger(name, event, source='', condition=''):
    return f'{{ config_id = 1000000 + {name[-4:] if name[-4:].isdigit() else 1}, name = "{name}", event = EventType.EVENT_{event}, source = "{source}", condition = "{condition}", action = "action_{name}", trigger_count = 0 }}'


def group_source(group_id, monsters, gadgets, variables, suites, triggers, functions=''):
    variables = [f'{{ config_id = {i}, name = "{name}", value = 0, no_refresh = false }}' for i, name in enumerate(variables, 1)]
    out = HEADER + f'local base_info = {{ group_id = {group_id} }}\n'
    for name, values in [('monsters', monsters), ('npcs', []), ('gadgets', gadgets), ('regions', []), ('variables', variables), ('triggers', triggers)]:
        out += name + ' = {\n' + ''.join('    ' + value + ',\n' for value in values) + '}\n'
    out += 'init_config = { suite = 1, end_suite = 0, rand_suite = false }\nsuites = {\n'
    for monster_ids, gadget_ids, trigger_names in suites:
        names = lua_list('"' + name + '"' for name in trigger_names)
        out += f'    {{ monsters = {lua_list(monster_ids)}, gadgets = {lua_list(gadget_ids)}, regions = {{}}, triggers = {names}, rand_weight = 100 }},\n'
    return out + '}\n' + functions


def wall_group(group_id):
    gadgets = [gadget(1001, 70350053, y=0), gadget(1002, 70350054, y=0)]
    names = ['MGC_SETTLE_1003']
    functions = f'''
function action_MGC_SETTLE_1003(context, evt)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {group_id}, 1001, GadgetState.Default)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {group_id}, 1002, GadgetState.Default)
    return 0
end
'''
    return group_source(group_id, [], gadgets, [], [([], [1001, 1002], names)], [trigger(names[0], 'DUNGEON_SETTLE')], functions)


def state_group(group_id):
    return group_source(group_id, [], [], ['stage', 'TPL_TIME'], [([], [], [])], [])


def start_group(group_id, state_id, wall_id, upper_id, lower_id, upper_suite, lower_suite, guard=False):
    config = 2001 if guard else 3001
    names = ['MGC_CREATE_2002', 'MGC_UPPER_2003', 'MGC_LOWER_2004']
    triggers = [trigger(names[0], 'GADGET_CREATE', condition='condition_' + names[0]),
                trigger(names[1], 'SELECT_OPTION', condition='condition_' + names[1]),
                trigger(names[2], 'SELECT_OPTION', condition='condition_' + names[2])]
    functions = f'''
function condition_MGC_CREATE_2002(context, evt) return evt.param1 == {config} end
function action_MGC_CREATE_2002(context, evt)
    local stage = ScriptLib.GetGroupVariableValueByGroup(context, "stage", {state_id})
    local option = 175
    if stage == 1 then option = 176 end
    if stage < 2 then ScriptLib.SetWorktopOptionsByGroupId(context, {group_id}, {config}, {{ option }}) end
    return 0
end
function condition_MGC_UPPER_2003(context, evt)
    return evt.param1 == {config} and evt.param2 == 175 and ScriptLib.GetGroupVariableValueByGroup(context, "stage", {state_id}) == 0
end
function condition_MGC_LOWER_2004(context, evt)
    return evt.param1 == {config} and evt.param2 == 176 and ScriptLib.GetGroupVariableValueByGroup(context, "stage", {state_id}) == 1
end
local function start_half(context, option, combat_group, suite)
    ScriptLib.SetIsAllowUseSkill(context, 1)
    ScriptLib.DelWorktopOptionByGroupId(context, {group_id}, {config}, option)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {group_id}, {config}, GadgetState.GearStop)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {wall_id}, 1001, GadgetState.GearStart)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {wall_id}, 1002, GadgetState.GearStart)
    ScriptLib.AddExtraGroupSuite(context, combat_group, suite)
    return 0
end
function action_MGC_UPPER_2003(context, evt) return start_half(context, 175, {upper_id}, {upper_suite}) end
function action_MGC_LOWER_2004(context, evt) return start_half(context, 176, {lower_id}, {lower_suite}) end
'''
    return group_source(group_id, [], [gadget(config, 70360010, z=8 if guard else 0)], [], [([], [config], names)], triggers, functions)


def monster_row(entry):
    p = entry['position']
    return f'{{ config_id = {entry["configId"]}, monster_id = {entry["monsterId"]}, level = {entry["level"]}, pos = {{ x = {p["x"]:.3f}, y = {p["y"]:.3f}, z = {p["z"]:.3f} }}, rot = {{ x = 0, y = {entry["yaw"]:.3f}, z = 0 }}, disableWander = true }}'


def combat_group(group_id, halves, state_id, wall_id, start_id, start_config, guard=False):
    # Each half has one challenge across all its waves; no half can settle the next half.
    names = ['MGC_LIVE_4001', 'MGC_DIE_4002', 'MGC_UP_SUCCESS_4003', 'MGC_LOW_SUCCESS_4004', 'MGC_FAIL_4005', 'MGC_FAIL_4006']
    triggers = [trigger(names[0], 'ANY_MONSTER_LIVE', condition='condition_' + names[0]),
                trigger(names[1], 'ANY_MONSTER_DIE', condition='condition_' + names[1]),
                trigger(names[2], 'CHALLENGE_SUCCESS', '1'), trigger(names[3], 'CHALLENGE_SUCCESS', '2'),
                trigger(names[4], 'CHALLENGE_FAIL', '1'), trigger(names[5], 'CHALLENGE_FAIL', '2')]
    suites = [([], [3024] if guard else [], names)]
    plans = []
    for half in halves:
        first_suite = len(suites) + 1
        for wave in half['waves']:
            suites.append(([entry['configId'] for entry in wave], [], names))
        plans.append((half, first_suite))
    monsters = [monster_row(entry) for half in halves for wave in half['waves'] for entry in wave]
    definition = ''
    for half, first_suite in plans:
        definition += f'    [{half["half"]}] = {{ first = {half["waves"][0][0]["configId"]}, suite = {first_suite}, waves = {len(half["waves"])}, kills = {sum(map(len, half["waves"]))} }},\n'
    functions = 'local plan = {\n' + definition + '}\n'
    functions += f'''
local function current_half(context)
    return ScriptLib.GetGroupVariableValueByGroup(context, "stage", {state_id}) + 1
end
function condition_MGC_LIVE_4001(context, evt)
    local half = current_half(context)
    return plan[half] ~= nil and evt.param1 == plan[half].first and ScriptLib.GetGroupVariableValue(context, "started") == 0
end
function action_MGC_LIVE_4001(context, evt)
    local half = current_half(context)
    ScriptLib.SetGroupVariableValue(context, "started", 1)
    ScriptLib.SetGroupVariableValue(context, "wave", 1)
'''
    if guard:
        functions += f'    return ScriptLib.ActiveChallenge(context, half, 188, {group_id}, plan[half].kills, 3024, 0)\n'
    else:
        functions += f'''    local seconds = 600
    if half == 2 then
        seconds = ScriptLib.GetGroupVariableValueByGroup(context, "TPL_TIME", {state_id})
        if seconds <= 0 then return -1 end
    end
    return ScriptLib.ActiveChallenge(context, half, 196 + half, seconds, {group_id}, plan[half].kills, 0)
'''
    functions += f'''end
function condition_MGC_DIE_4002(context, evt)
    local half = current_half(context)
    local wave = ScriptLib.GetGroupVariableValue(context, "wave")
    return plan[half] ~= nil and ScriptLib.GetGroupVariableValue(context, "started") == 1 and wave > 0 and ScriptLib.GetGroupMonsterCount(context) == 0 and wave < plan[half].waves
end
function action_MGC_DIE_4002(context, evt)
    local half = current_half(context)
    local wave = ScriptLib.GetGroupVariableValue(context, "wave") + 1
    ScriptLib.SetGroupVariableValue(context, "wave", wave)
    ScriptLib.AddExtraGroupSuite(context, {group_id}, plan[half].suite + wave - 1)
    return 0
end
local function open_walls(context)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {wall_id}, 1001, GadgetState.Default)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {wall_id}, 1002, GadgetState.Default)
end
function action_MGC_UP_SUCCESS_4003(context, evt)
    ScriptLib.SetGroupVariableValueByGroup(context, "TPL_TIME", evt.param2, {state_id})
    ScriptLib.SetGroupVariableValueByGroup(context, "stage", 1, {state_id})
    ScriptLib.SetGroupVariableValue(context, "started", 0)
    ScriptLib.SetGroupVariableValue(context, "wave", 0)
    ScriptLib.SetIsAllowUseSkill(context, 0)
    ScriptLib.TowerMirrorTeamSetUp(context, 2)
    ScriptLib.SetGroupGadgetStateByConfigId(context, {start_id}, {start_config}, GadgetState.Default)
    ScriptLib.SetWorktopOptionsByGroupId(context, {start_id}, {start_config}, {{176}})
    open_walls(context)
    return 0
end
function action_MGC_LOW_SUCCESS_4004(context, evt)
    ScriptLib.SetGroupVariableValueByGroup(context, "stage", 2, {state_id})
    open_walls(context)
    return 0
end
function action_MGC_FAIL_4005(context, evt) open_walls(context) return ScriptLib.CauseDungeonFail(context) end
function action_MGC_FAIL_4006(context, evt) open_walls(context) return ScriptLib.CauseDungeonFail(context) end
'''
    gadgets = [gadget(3024, 70350450)] if guard else []
    return group_source(group_id, monsters, gadgets, ['wave', 'started'], suites, triggers, functions), plans


def select_monster(describe_id, monsters, describes):
    if describe_id in SPECIAL_VARIANTS:
        monster_id, reason = SPECIAL_VARIANTS[describe_id]
        row = monsters[monster_id]
        if describe_id == 21003:
            if describe_id not in row.get('affix', []): raise ValueError('Baptist element affix is missing')
        else:
            original = describes[describe_id]
            base = describes[row['describeId']]
            if original['icon'] != base['icon']: raise ValueError('special variant icon differs')
        return row, reason
    candidates = [row for row in monsters.values() if row.get('describeId') == describe_id]
    native_family = [row for row in candidates if row['id'] // 100 == 200000 + describe_id]
    if not native_family: raise ValueError(f'No ordinary MonsterExcel family for describe {describe_id}')
    return min(native_family, key=lambda row: row['id']), 'Lowest existing regular variant in the exact MonsterExcel describe family'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--resources', type=Path, default=Path(__file__).resolve().parents[2] / 'resources')
    parser.add_argument('--schedule-id', type=int, default=124)
    args = parser.parse_args()
    root = args.resources.resolve()
    excel = lambda name: read_json(root / f'ExcelBinOutput/{name}ExcelConfigData.json')
    schedule = next(row for row in excel('TowerSchedule') if row['scheduleId'] == args.schedule_id)
    floor_ids = [value for part in schedule['LHOGNLPBILP'] for value in part.get('floorList', [])]
    floors = {row['floorId']: row for row in excel('TowerFloor')}
    levels = excel('TowerLevel')
    dungeons = {row['id']: row for row in excel('Dungeon')}
    monsters = {row['id']: row for row in excel('Monster')}
    describes = {row['id']: row for row in excel('MonsterDescribe')}
    files, manifest = {}, []
    for floor_id in floor_ids:
        floor = floors[floor_id]
        for level in sorted((row for row in levels if row['levelGroupId'] == floor['levelGroupId']), key=lambda row: row['levelIndex']):
            scene = dungeons[level['dungeonId']]['sceneId']
            directory = root / f'Scripts/Scene/{scene}'
            if not (directory / f'scene{scene}.lua').is_file(): raise ValueError(f'Missing original scene stub: {scene}')
            guard = level['conds'][0]['towerCondType'] == 'TOWER_COND_LEFT_HP_GREATER_THAN'
            base = 200000000 + scene * 1000
            state_id, wall_id, start_id = (base + 1, base + 4, base + 2) if guard else (base + 2, base + 1, base + 3)
            upper_id, lower_id = (base + 3, base + 3) if guard else (base + 4, base + 5)
            previews = {row['id']: row for row in read_json(root / f'BinOutput/MonsterPreview/MonsterPreview_{level["towerMonsterPreview"]}.json')}
            halves = []
            for half in (1, 2):
                preview = previews[level[f'towerMonsterPreviewId{half}']]
                entries = []
                for index, info in enumerate(preview['monsterPreviewInfo']):
                    row, reason = select_monster(info['monsterPreviewDescribeId'], monsters, describes)
                    config = (3001 + index if half == 1 else 3101 + index) if guard else half * 1000 + 3001 + index
                    slot = index % 3
                    x, z = [(0, -9), (-6, -5), (6, -5)][slot]
                    entries.append({'configId': config, 'describeId': info['monsterPreviewDescribeId'], 'monsterId': row['id'],
                                    'monsterName': row['monsterName'], 'variantReason': reason, 'level': info['reviseLevel'],
                                    'position': {'x': x, 'y': -0.102, 'z': z}, 'yaw': round(math.degrees(math.atan2(-x, -z)), 3)})
                if not entries: raise ValueError(f'Empty confirmed preview {scene}/{half}')
                halves.append({'half': half, 'previewId': preview['id'], 'waves': [entries[i:i + 3] for i in range(0, len(entries), 3)]})
            groups = {state_id: state_group(state_id), wall_id: wall_group(wall_id)}
            if guard:
                if level['conds'][0]['argumentList'][:2] != [upper_id, 3024]: raise ValueError('Guard objective group/config mismatch')
                groups[upper_id], plans = combat_group(upper_id, halves, state_id, wall_id, start_id, 2001, True)
                upper_suite, lower_suite = plans[0][1], plans[1][1]
            else:
                groups[upper_id], plans = combat_group(upper_id, [halves[0]], state_id, wall_id, start_id, 3001)
                upper_suite = plans[0][1]
                groups[lower_id], plans = combat_group(lower_id, [halves[1]], state_id, wall_id, start_id, 3001)
                lower_suite = plans[0][1]
            groups[start_id] = start_group(start_id, state_id, wall_id, upper_id, lower_id, upper_suite, lower_suite, guard)
            for group_id, source in groups.items(): files[directory / f'scene{scene}_group{group_id}.lua'] = source
            block = HEADER + 'groups = {\n' + ''.join(f'    {{ id = {group_id}, refresh_id = {1001 if group_id in (upper_id, lower_id) else 1}, pos = {{ x = 0, y = -0.102, z = 0 }} }},\n' for group_id in sorted(groups)) + '}\n'
            files[directory / f'scene{scene}_block{scene}.lua'] = block
            manifest.append({'floorIndex': floor['floorIndex'], 'floorId': floor_id, 'chamber': level['levelIndex'], 'sceneId': scene,
                             'dungeonId': level['dungeonId'], 'guardObjective': {'groupId': upper_id, 'configId': 3024, 'gadgetId': 70350450} if guard else None,
                             'authorship': 'Confirmed official enemy kinds/levels; MGC-authored counts/waves/coordinates/flow', 'halves': halves})
    for path, content in files.items():
        if path.exists() and not path.read_text(encoding='utf-8-sig').startswith(MARKER):
            raise ValueError(f'Refusing to replace an existing non-generated script: {path}')
    for path, content in files.items(): path.write_text(content, encoding='utf-8', newline='\n')
    output = root / f'Scripts/Scene/mgc-schedule-{args.schedule_id}.json'
    output.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(files)} Lua files for {len(manifest)} chambers; enemy kinds/levels from previews, all waves and positions authored by MGC.')
    print(f'Variant and wave manifest: {output}')


if __name__ == '__main__':
    main()
